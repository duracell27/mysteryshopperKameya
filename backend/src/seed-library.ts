// ── Helpers ──────────────────────────────────────────────────────────────────

function coverUrl(filename: string): string {
  return `/uploads/books/${filename}`;
}

function fixNewlines() {
  if (!fs.existsSync(BOOKS_DIR)) return;
  for (const file of fs.readdirSync(BOOKS_DIR)) {
    if (file.includes('\n')) {
      const clean = file.replace(/\n/g, '');
      fs.renameSync(path.join(BOOKS_DIR, file), path.join(BOOKS_DIR, clean));
      console.log(`  ✂️  перейменовано: "${file.replace(/\n/g, '\\n')}" → "${clean}"`);
    }
  }
}

