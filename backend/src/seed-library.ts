async function seedLibrary() {
  await connectDB();

  // 1. Fix filenames with newlines
  console.log('\n📂 Перевірка імен файлів обкладинок...');
  fixNewlines();

  // 2. Genres
  console.log('\n📚 Жанри...');
  const genreMap: Record<string, string> = {};
  for (const name of GENRES) {
    const existing = await BookGenre.findOne({ name });
    if (existing) {
      genreMap[name] = existing._id.toString();
      console.log(`  ↩️  вже є: ${name}`);
    } else {
      const g = await BookGenre.create({ name });
      genreMap[name] = g._id.toString();
      console.log(`  ✅ додано: ${name}`);
    }
  }

  // 3. Books
  console.log('\n📖 Книги...');
  let added = 0;
  let skipped = 0;
  for (const b of BOOKS) {
    const exists = await Book.findOne({ title: b.title });
    if (exists) { skipped++; continue; }
    const url = coverUrl(b.cover);
    await Book.create({
      title:      b.title,
      author:     b.author,
      genreId:    genreMap[b.genre],
      annotation: b.annotation,
      coverUrl:   url,
    });
    added++;
    console.log(`  ✅ ${b.title}`);
  }

  console.log(`\n✨ Готово: додано ${added} книг, пропущено ${skipped} (вже існували).`);
  process.exit(0);
}

seedLibrary().catch((e) => {
  console.error(e);
  process.exit(1);
});
